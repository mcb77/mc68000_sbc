#!/usr/bin/env python3
"""Write entries.inc from a vasm listing.

The slot addresses are fixed. The script refuses a listing whose ENTRIES
symbol is not $100400, because uploaded code calls those slots.
"""
import re
import sys

SLOTS = ("SERIAL_TX", "SERIAL_RX", "SERIAL_POLL", "SERIAL_RX_TIMED")
ENTRY_BASE = 0x100400


def symbols(path):
    found = {}
    for line in open(path, encoding="latin1"):
        match = re.match(r"^(\w+)\s+A:([0-9A-Fa-f]+)", line)
        if match:
            found[match.group(1)] = int(match.group(2), 16)
    return found


def main():
    listing, dest = sys.argv[1], sys.argv[2]
    sym = symbols(listing)
    entries = sym.get("ENTRIES")
    if entries != ENTRY_BASE:
        sys.exit(f"ENTRIES is {entries}, expected ${ENTRY_BASE:06X}")
    missing = [name for name in SLOTS if name not in sym]
    if missing:
        sys.exit(f"listing has no symbol: {', '.join(missing)}")
    names = ("ENTRY_TX", "ENTRY_RX", "ENTRY_POLL", "ENTRY_RX_TIMED")
    lines = [
        "; Generated by gen_entries.py. Do not edit.",
        "; Call MOVE.L (ENTRY_TX).L,An / JSR (An). The slots do not move.",
        "; Targets in the comments are this listing only.",
    ]
    for name, slot, addr in zip(names, SLOTS, range(ENTRY_BASE, ENTRY_BASE + 16, 4)):
        lines.append(f"{name:<16} EQU ${addr:08X}  ; {slot} ${sym[slot]:08X}")
    lines.append("")
    text = "\n".join(lines)
    open(dest, "w", encoding="ascii").write(text)
    print(text, end="")


if __name__ == "__main__":
    main()
